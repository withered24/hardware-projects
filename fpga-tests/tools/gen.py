"""gen.py: generate a suite's replay harness (Quartus project + simulation testbench).

    python gen.py <suite>

writes builds/<suite>/:
  src/            the DUT's sources after FPGA-only patches and qcompat.py
  replay_top.sv   CLOCK_50 -> sequencer + trace RAMs + gated clock + DUT
  tb_replay.sv    simulation testbench: loads chunk files in place of JTAG
  replay.qpf/qsf/sdc
  meta.json       vector widths, RAM names, suite id (read by replay.py)
"""
import json
import sys
import zlib
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
FT = TOOLS.parent
sys.path.insert(0, str(TOOLS))
from qcompat import convert  # noqa: E402
from suites import FPGA, SUITES, sources_for  # noqa: E402

PH = 8                    # base cycles per DUT edge; base clock = CLOCK_50
DEVICE = "EP4CE115F29C7"
PINS = {"CLOCK_50": "PIN_Y2", "LEDG[0]": "PIN_E21", "LEDG[1]": "PIN_E22",
        "LEDG[2]": "PIN_E25", "LEDG[3]": "PIN_E24"}


def layout(name: str) -> dict:
    s, f = SUITES[name], FPGA[name]
    ports = json.loads((FT / "traces" / name / "ports.json").read_text())
    ins = [p for p in ports if p["dir"] == "input" and p["name"] != "clk"]
    ins += [{"name": n, "dir": "input", "width": 1} for n in f.get("sideband", [])]
    outs = [p for p in ports if p["dir"] == "output"]

    def place(lst):
        tot = sum(p["width"] for p in lst)
        pos, res = tot, []
        for p in lst:
            pos -= p["width"]
            res.append({**p, "lsb": pos})
        return tot, res

    nin, ins = place(ins)
    nout, outs = place(outs)
    niw, now = (nin + 31) // 32, (nout + 31) // 32
    sid = zlib.crc32(json.dumps([name, ins, outs]).encode()) & 0xFFFFFFFF
    return dict(suite=name, top=s["top"], params=s.get("params", {}), nin=nin, nout=nout,
                niw=niw, now=now, aw=f["aw"], ph=PH, suite_id=sid, ins=ins, outs=outs,
                harness=f.get("harness_ports", {}),
                s_names=[f"S{k:02d}" for k in range(niw)], r_names=[f"R{k:02d}" for k in range(now)])


def sv_param(v):
    return str(v) if isinstance(v, int) else v


def gen_top(m: dict) -> str:
    conn = [".clk (dclk)"]
    conn += [f".{p['name']} (in_vec[{p['lsb'] + p['width'] - 1}:{p['lsb']}])" for p in m["ins"]]
    conn += [f".{p['name']} (out_vec[{p['lsb'] + p['width'] - 1}:{p['lsb']}])" for p in m["outs"]]
    conn += [f".{k} ({v})" for k, v in m["harness"].items()]
    params = ", ".join(f".{k}({sv_param(v)})" for k, v in m["params"].items())
    params = f" #({params})" if params else ""
    s_rams = "\n".join(
        f"    rt_ram #(.AW(AW), .NAME(\"{n}\")) u_{n.lower()} (.clk(clk), .addr(s_addr), .we(1'b0), "
        f".wdata(32'd0), .q(s_q[{32 * k + 31}:{32 * k}]));" for k, n in enumerate(m["s_names"]))
    r_rams = "\n".join(
        f"    rt_ram #(.AW(AW), .NAME(\"{n}\")) u_{n.lower()} (.clk(clk), .addr(s_addr), .we(r_we), "
        f".wdata(r_d[{32 * k + 31}:{32 * k}]), .q());" for k, n in enumerate(m["r_names"]))
    pad = ("    assign r_d[NOW*32-1:NOUT] = '0;\n" if m["now"] * 32 > m["nout"] else "")
    return f"""// replay_top.sv: generated by tools/gen.py for suite {m['suite']}; do not edit
//
// DUT {m['top']}{params}: {m['nin']} input bits ({m['niw']} stimulus RAMs), {m['nout']} output bits
// ({m['now']} response RAMs), {2 ** m['aw']} entries per chunk, {m['ph']} base cycles per DUT edge.
// LEDG[0] heartbeat, LEDG[1] busy, LEDG[2] DUT edge count bit 20, LEDG[3] ~busy.

module replay_top (
    input  logic       CLOCK_50,
    output logic [3:0] LEDG
);
    localparam int NIN = {m['nin']}, NOUT = {m['nout']}, NIW = {m['niw']}, NOW = {m['now']}, AW = {m['aw']};

    logic clk, dclk, dclk_en, busy, r_we;
    logic [3:0]        ph;
    logic [31:0]       edges;
    logic [AW-1:0]     s_addr;
    logic [NIW*32-1:0] s_q;
    logic [NIN-1:0]    in_vec;
    wire  [NOUT-1:0]   out_vec;             // a net: every DUT output port drives a slice
    wire  [NOW*32-1:0] r_d;
    assign clk = CLOCK_50;
    assign r_d[NOUT-1:0] = out_vec;
{pad}
    replay_seq #(.NIN(NIN), .NIW(NIW), .AW(AW), .PH({m['ph']}), .SUITE_ID(32'h{m['suite_id']:08X})) u_seq (
        .clk(clk), .s_addr(s_addr), .s_q(s_q), .r_we(r_we), .in_vec(in_vec),
        .dclk_en(dclk_en), .ph(ph), .busy(busy), .edges(edges));

{s_rams}
{r_rams}

    dclk_gate u_gate (.clk(clk), .ena(dclk_en), .gclk(dclk));

    {m['top']}{params} u_dut (
        {(',' + chr(10) + '        ').join(conn)}
    );

    logic [24:0] hb = '0;
    always_ff @(posedge clk) hb <= hb + 1'b1;
    assign LEDG = {{~busy, edges[20], busy, hb[24]}};
endmodule
"""


def gen_tb(m: dict) -> str:
    loads = "\n".join(f'            $readmemh({{cdir, "/{n.lower()}.hex"}}, u_top.u_{n.lower()}.mem, 0, cnt - 1);'
                      for n in m["s_names"])
    dumps = "\n".join(f'            $writememb({{odir, "/{n.lower()}.hex"}}, u_top.u_{n.lower()}.mem, 0, cnt - 1);'
                      for n in m["r_names"])
    return f"""// tb_replay.sv: generated by tools/gen.py; simulation of the replay harness.
// The chunk list (+LIST=file) has lines "<chunk dir> <out dir> <count>". Chunk
// files are loaded straight into the stimulus RAMs and responses dumped from
// the response RAMs: exactly what the host does over JTAG.
`timescale 1ns/1ps
module tb_replay;
    logic clk = 1'b0;
    always #10 clk = ~clk;
    replay_top u_top (.CLOCK_50(clk), .LEDG());

    string list, cdir, odir;
    int fd, cnt, tok, nch;
    initial begin
        if (!$value$plusargs("LIST=%s", list)) $fatal(1, "+LIST=<chunk list> missing");
        fd = $fopen(list, "r");
        tok = 0;
        nch = 0;
        repeat (4) @(posedge clk);
        while ($fscanf(fd, "%s %s %d\\n", cdir, odir, cnt) == 3) begin
{loads}
            u_top.u_seq.u_ctrl.mem[1] = cnt;
            repeat (4) @(posedge clk);
            tok = tok + 1;
            u_top.u_seq.u_ctrl.mem[0] = tok;
            wait (u_top.u_seq.busy);
            wait (!u_top.u_seq.busy);
            repeat (2) @(posedge clk);
{dumps}
            nch = nch + 1;
        end
        $display("tb_replay: %0d chunks, %0d DUT edges", nch, u_top.u_seq.edges);
        $finish;
    end
endmodule
"""


def gen_qsf(m: dict, files: list[Path], fpga_rtl: list[Path]) -> str:
    lines = [f'set_global_assignment -name FAMILY "Cyclone IV E"',
             f"set_global_assignment -name DEVICE {DEVICE}",
             "set_global_assignment -name TOP_LEVEL_ENTITY replay_top",
             "set_global_assignment -name PROJECT_OUTPUT_DIRECTORY output",
             'set_global_assignment -name VERILOG_MACRO "SYNTHESIS=1"',
             "set_global_assignment -name SDC_FILE replay.sdc",
             'set_global_assignment -name RESERVE_ALL_UNUSED_PINS_WEAK_PULLUP "AS INPUT TRI-STATED"',
             "set_global_assignment -name OPTIMIZATION_MODE \"HIGH PERFORMANCE EFFORT\"",
             'set_global_assignment -name TIMING_ANALYZER_MULTICORNER_ANALYSIS ON',
             "set_global_assignment -name NUM_PARALLEL_PROCESSORS 4"]
    for f in fpga_rtl + files + [Path("replay_top.sv")]:
        lines.append(f'set_global_assignment -name SYSTEMVERILOG_FILE "{f.as_posix()}"')
    for pin, loc in PINS.items():
        lines.append(f"set_location_assignment {loc} -to {pin}")
        lines.append(f'set_instance_assignment -name IO_STANDARD "3.3-V LVTTL" -to {pin}')
    return "\n".join(lines) + "\n"


def gen_sdc(m: dict) -> str:
    ph = m["ph"]
    return f"""# replay.sdc: generated by tools/gen.py. Base clock 50 MHz; the DUT clock
# (dclk) is the base clock gated to one edge every {ph} base cycles, at the
# end of phase {ph - 1}. Phase schedule (edges E0..E{ph - 1} end phases 0..{ph - 1}):
#   in_vec launched at E1; DUT edge at E{ph - 1};
#   FPGA-only DUT memories read at E{ph - 4}..E{ph - 2} (see patches/).
create_clock -name base -period 20.000 [get_ports CLOCK_50]
create_generated_clock -name dclk -source [get_ports CLOCK_50] [get_pins -compatibility_mode {{u_gate|u_ctrl|outclk}}]
derive_clock_uncertainty

# DUT register to DUT register: one DUT edge per {ph} base cycles
set_multicycle_path -setup -end -from [get_clocks dclk] -to [get_clocks dclk] {ph}
set_multicycle_path -hold  -end -from [get_clocks dclk] -to [get_clocks dclk] {ph - 1}
# base-clock registers into DUT registers: in_vec (E1) and FPGA-only memory
# holding registers (latest E{ph - 3}) reach the DUT edge E{ph - 1}: at least 2 cycles
set_multicycle_path -setup -end -from [get_clocks base] -to [get_clocks dclk] 2
set_multicycle_path -hold  -end -from [get_clocks base] -to [get_clocks dclk] 1
# DUT registers (E{ph - 1}) into base-clock registers: response RAM at E{ph - 1}, FPGA-only
# memory addresses at E{ph - 4} or later: at least {ph - 3} cycles
set_multicycle_path -setup -end -from [get_clocks dclk] -to [get_clocks base] {ph - 3}
set_multicycle_path -hold  -end -from [get_clocks dclk] -to [get_clocks base] {ph - 4}
# in_vec (E1) through DUT logic into base-clock registers (E{ph - 4} or later)
set_multicycle_path -setup -end -from [get_registers {{*u_seq|in_vec*}}] -to [get_clocks base] {ph - 5}
set_multicycle_path -hold  -end -from [get_registers {{*u_seq|in_vec*}}] -to [get_clocks base] {ph - 6}
"""


def generate(name: str) -> dict:
    m = layout(name)
    bd = FT / "builds" / name
    src = bd / "src"
    src.mkdir(parents=True, exist_ok=True)
    files = []
    for f in sources_for(name, patched=True):
        out = src / f.name
        out.write_text(convert(f.read_text()), newline="\n")
        files.append(out.relative_to(bd))
    rtl = FT / "fpga" / "rtl"
    fpga_rtl = [rtl / "qcompat_pkg.sv", rtl / "rt_ram.sv", rtl / "dclk_gate.sv", rtl / "replay_seq.sv"]
    (bd / "replay_top.sv").write_text(gen_top(m), newline="\n")
    (bd / "tb_replay.sv").write_text(gen_tb(m), newline="\n")
    (bd / "replay.qpf").write_text('PROJECT_REVISION = "replay"\n')
    (bd / "replay.qsf").write_text(gen_qsf(m, files, fpga_rtl))
    (bd / "replay.sdc").write_text(gen_sdc(m))
    m["sim_sources"] = [str(p) for p in fpga_rtl] + [str(bd / f) for f in files] + \
        [str(bd / "replay_top.sv"), str(bd / "tb_replay.sv")]
    (bd / "meta.json").write_text(json.dumps(m, indent=1))
    print(f"[gen] {name}: in {m['nin']} bits / {m['niw']} RAMs, out {m['nout']} bits / {m['now']} RAMs, "
          f"{2 ** m['aw']} entries/chunk, id {m['suite_id']:08X} -> {bd}")
    return m


if __name__ == "__main__":
    for n in sys.argv[1:] or list(SUITES):
        generate(n)
